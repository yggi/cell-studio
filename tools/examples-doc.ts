// docs/examples.md, written from examples/*.cells: the catalogue can't drift from the files.
// `npm run docs:examples` rewrites it; src/examplesDoc.test.ts fails when the checked-in page differs.
import { readFileSync } from 'node:fs';
import { durationText, mainLength } from '../src/engine/duration';
import { pieceMeta } from '../src/engine/parser';
import { LADDER } from '../src/engine/ladder';
import { parseTag, tagName, TUTORIAL } from '../src/engine/tags';
import { buildExamplesMeta, type ExampleMeta } from './examples-index';

/** The level= of the sound card, in dB (the examples all carry one). */
const levelOf = (source: string): string => /\blevel=(-?[\d.]+)/.exec(source)?.[1] ?? '';

const cell = (s: string): string => s.replace(/\|/g, '\\|');

/** How long the piece is: its length, `∞` for a loop with no end, `~` when chance is in it. */
function lengthOf(e: ExampleMeta): string {
  const t = e.time;
  const main = mainLength(t);
  if (main === null) return '';
  const text = durationText(main);
  return t.ends !== null ? text : `${text} loop`;
}

/** The page: the tutorial, rung by rung; then the pieces, one section per genre (the first genre tag), in the order the genres first appear in the library. */
export function buildExamplesDoc(dir = 'examples'): string {
  const all = buildExamplesMeta(dir);
  const tutorial = all.filter((e) => e.tags.includes(TUTORIAL)).sort((a, b) => (a.rung ?? 0) - (b.rung ?? 0));
  const index = all.filter((e) => !e.tags.includes(TUTORIAL));
  const firstGenre = (e: ExampleMeta) => {
    const g = e.tags.map(parseTag).find((t) => t.kind === 'genre');
    return g?.name ?? 'other';
  };
  const groups = new Map<string, ExampleMeta[]>();
  for (const e of index) {
    const g = firstGenre(e);
    groups.set(g, [...(groups.get(g) ?? []), e]);
  }
  const out: string[] = [
    '# Examples',
    '',
    `The pieces that ship with Cell studio, one plain-text file each in \`examples/*.cells\` (${all.length} of them): first the tutorial, ${tutorial.length} rungs in order, then the pieces, grouped by their first genre tag and listed in the library's order. Open one from the title in the header ([ui/library.md](ui/library.md)).`,
    '',
    '<!-- Generated by tools/examples-doc.ts from examples/*.cells: run `npm run docs:examples`, do not edit. A test fails when it is out of date. -->',
    '',
    '## Tutorial',
    '',
    'Each rung introduces one concept and uses only what the rungs before it introduced; together they cover every form of the [syntax reference](language/reference.md), each once ([display.md](language/display.md#the-tutorial-rung)).',
    '',
    '| rung | piece | file | introduces | about | level | length |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const e of tutorial) {
    const source = readFileSync(`${dir}/${e.key}.cells`, 'utf8');
    out.push(
      `| ${e.rung} | ${cell(e.title)} | [\`${e.key}\`](../examples/${e.key}.cells) | ${cell(LADDER[(e.rung ?? 0) - 1]?.concept ?? '')} | ${cell(pieceMeta(source)?.description ?? e.description)} | ${levelOf(source)} | ${lengthOf(e)} |`,
    );
  }
  for (const [genre, items] of groups) {
    out.push('', `## ${genre[0].toUpperCase()}${genre.slice(1)}`, '');
    out.push('| piece | file | tags | about | level | length |', '|---|---|---|---|---|---|');
    for (const e of items) {
      const source = readFileSync(`${dir}/${e.key}.cells`, 'utf8');
      const tags = e.tags.map(tagName).join(', ');
      out.push(
        `| ${cell(e.title)} | [\`${e.key}\`](../examples/${e.key}.cells) | ${cell(tags)} | ${cell(pieceMeta(source)?.description ?? e.description)} | ${levelOf(source)} | ${lengthOf(e)} |`,
      );
    }
  }
  return out.join('\n') + '\n';
}
