// docs/examples.md, written from examples/*.cells: the catalogue can't drift from the files.
// `npm run docs:examples` rewrites it; src/examplesDoc.test.ts fails when the checked-in page differs.
import { readFileSync } from 'node:fs';
import { durationText, mainLength } from '../src/engine/duration';
import { pieceMeta } from '../src/engine/parser';
import { parseTag, tagName } from '../src/engine/tags';
import { buildExamplesIndex, type ExampleInfo } from './examples-index';

/** The level= of the sound card, in dB (the examples all carry one). */
const levelOf = (source: string): string => /\blevel=(-?[\d.]+)/.exec(source)?.[1] ?? '';

const cell = (s: string): string => s.replace(/\|/g, '\\|');

/** How long the piece is: its length, `∞` for a loop with no end, `~` when chance is in it. */
function lengthOf(e: ExampleInfo): string {
  const t = e.time;
  const main = mainLength(t);
  if (main === null) return '';
  const text = durationText(main);
  return t.ends !== null ? text : `${text} loop`;
}

/** The page: one section per genre (the first genre tag), in the order the genres first appear in the library. */
export function buildExamplesDoc(dir = 'examples'): string {
  const index = buildExamplesIndex(dir);
  const firstGenre = (e: ExampleInfo) => {
    const g = e.tags.map(parseTag).find((t) => t.kind === 'genre');
    return g?.name ?? 'other';
  };
  const groups = new Map<string, ExampleInfo[]>();
  for (const e of index) {
    const g = firstGenre(e);
    groups.set(g, [...(groups.get(g) ?? []), e]);
  }
  const out: string[] = [
    '# Examples',
    '',
    `The pieces that ship with Cell studio, one plain-text file each in \`examples/*.cells\` (${index.length} of them), grouped by their first genre tag and listed in the library's order. Open one from the title in the header ([ui/library.md](ui/library.md)).`,
    '',
    '<!-- Generated by tools/examples-doc.ts from examples/*.cells: run `npm run docs:examples`, do not edit. A test fails when it is out of date. -->',
  ];
  for (const [genre, items] of groups) {
    out.push('', `## ${genre[0].toUpperCase()}${genre.slice(1)}`, '');
    out.push('| piece | file | tags | about | level | length |', '|---|---|---|---|---|---|');
    for (const e of items) {
      const source = readFileSync(`${dir}/${e.key}.cells`, 'utf8');
      const tags = e.tags.map(tagName).join(', ');
      out.push(
        `| ${cell(e.title)} | [\`${e.key}\`](../examples/${e.key}.cells) | ${cell(tags)} | ${cell(pieceMeta(source)?.description ?? e.description)} | ${levelOf(source)} | ${lengthOf(e)} |`,
      );
    }
  }
  return out.join('\n') + '\n';
}
