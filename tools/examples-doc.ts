// docs/examples.md, written from examples/*.md: the catalogue can't drift from the files.
// `npm run docs:examples` rewrites it; src/examplesDoc.test.ts fails when the checked-in page differs.
import { durationText, mainLength } from '@yggi/cells/engine/duration';
import { TIERS } from '@yggi/cells/engine/ladder';
import { parseTag, tagName, TUTORIAL } from '@yggi/cells/engine/tags';
import { buildExamplesMeta, EXAMPLES_DIR, type ExampleMeta } from './examples-index';

/** The sound card's postgain= (linear): 1 when its card leaves it out, .8 when it writes none (the built-in card, decision 028; none when it writes only MIDI cards). */
const postgainOf = (source: string): string => {
  // (the line that is the card: map=sample outside the quotes, not a note that mentions it)
  const card = source
    .split('\n')
    .map((l) => l.replace(/"[^"]*"/g, '""'))
    .find((l) => /^&\S+.*\bmap=sample\b/.test(l));
  if (card === undefined) return /\bmap=midi\b/.test(source) ? '' : '.8';
  return /\bpostgain=(\.?\d[\d.]*)/.exec(card)?.[1] ?? '1';
};

const cell = (s: string): string => s.replace(/\|/g, '\\|');

/** How long the piece is: its length, `∞` for a loop with no end, `~` when chance is in it. */
function lengthOf(e: ExampleMeta): string {
  const t = e.time;
  const main = mainLength(t);
  if (main === null) return '';
  const text = durationText(main);
  return t.ends !== null ? text : `${text} loop`;
}

/** The page: the tutorial, tier by tier; then the pieces, one section per genre (the first genre tag), in the order the genres first appear in the library. */
export function buildExamplesDoc(dir = EXAMPLES_DIR): string {
  const all = buildExamplesMeta(dir);
  const tutorial = all.filter((e) => e.tags.includes(TUTORIAL)).sort((a, b) => (a.tier ?? 0) - (b.tier ?? 0));
  const index = all.filter((e) => !e.tags.includes(TUTORIAL));
  const firstGenre = (e: ExampleMeta) => {
    const g = e.tags.map(parseTag).find((t) => t.kind === 'genre');
    return g?.name ?? 'other';
  };
  const groups = new Map<string, typeof all>();
  for (const e of index) {
    const g = firstGenre(e);
    groups.set(g, [...(groups.get(g) ?? []), e]);
  }
  const out: string[] = [
    '# Examples',
    '',
    `The pieces that ship with Cell studio, one piece file each in [cells' \`examples/\`](https://github.com/yggi/cells/tree/main/examples) (${all.length} of them): first the tutorial, ${tutorial.length} pieces in ${TIERS.length} tiers, then the pieces, grouped by their first genre tag and listed in the library's order. Open one from the title in the header ([ui/library.md](ui/library.md)).`,
    '',
    '<!-- Generated by tools/examples-doc.ts from examples/*.md: run `npm run docs:examples`, do not edit. A test fails when it is out of date. -->',
    '',
    '## Tutorial',
    '',
    'A tier is a stretch of the language; its pieces together show all of what it introduces and use nothing from a later tier. The numbers of the tiers are stable: a piece added to a tier changes none ([display.md](https://github.com/yggi/cells/blob/main/docs/language/display.md#the-tutorial-tier)).',
  ];
  TIERS.forEach((tier, i) => {
    out.push('', `### Tier ${i + 1} · ${tier.name}`, '', `Introduces ${tier.concept}.`, '', '| piece | file | about | postgain | length |', '|---|---|---|---|---|');
    // (the pieces of a tier in the library's order)
    for (const e of tutorial.filter((t) => t.tier === i + 1)) {
      out.push(
        `| ${cell(e.title)} | [\`${e.key}\`](https://github.com/yggi/cells/blob/main/examples/${e.key}.md) | ${cell(e.description)} | ${postgainOf(e.source)} | ${lengthOf(e)} |`,
      );
    }
  });
  for (const [genre, items] of groups) {
    out.push('', `## ${genre[0].toUpperCase()}${genre.slice(1)}`, '');
    out.push('| piece | file | tags | about | postgain | length |', '|---|---|---|---|---|---|');
    for (const e of items) {
      const tags = e.tags.map(tagName).join(', ');
      out.push(
        `| ${cell(e.title)} | [\`${e.key}\`](https://github.com/yggi/cells/blob/main/examples/${e.key}.md) | ${cell(tags)} | ${cell(e.description)} | ${postgainOf(e.source)} | ${lengthOf(e)} |`,
      );
    }
  }
  return out.join('\n') + '\n';
}
